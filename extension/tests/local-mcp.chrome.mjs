// Actual Agent, unpacked Extension and official MCP client; isolated browser only.
import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { mkdtemp, rm, cp, readFile, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { dirname, basename, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { spawn } from 'node:child_process';
import { Client } from '../../cloudflare-worker/node_modules/@modelcontextprotocol/sdk/dist/esm/client/index.js';
import { StreamableHTTPClientTransport } from '../../cloudflare-worker/node_modules/@modelcontextprotocol/sdk/dist/esm/client/streamableHttp.js';

const require=createRequire(import.meta.url);
const {chromium}=require(process.env.RESEARCHTUBE_PLAYWRIGHT_MODULE||'playwright');
const root=fileURLToPath(new URL('../../',import.meta.url));
const folder=await mkdtemp(join(tmpdir(),'researchtube-local-mcp-'));
const ID='jnnhjpkdhmghpbgfcalbhmkagdeelgnp',EXT='chrome-extension://'+ID;
let browser,agent,client;
const errors=[];
try {
  const program=`import asyncio,sys\nfrom pathlib import Path\nfrom agent import researchtube_agent as a\na.WORKSPACE_PATH=Path(sys.argv[1]);a.WORKSPACE_PATH.mkdir();a.initialize_health_snapshot()\nasync def main():\n s=await asyncio.start_server(a.handle_client,'127.0.0.1',0)\n print('TEST_PORT='+str(s.sockets[0].getsockname()[1]),flush=True)\n async with s: await s.serve_forever()\nasyncio.run(main())`;
  agent=spawn(process.env.RESEARCHTUBE_PYTHON||'python',['-X','utf8','-u','-c',program,join(folder,'workspace')],{cwd:root,windowsHide:true,stdio:['ignore','pipe','pipe']});
  agent.stderr.on('data',data=>errors.push(data.toString()));
  const port=await new Promise((resolve,reject)=>{
    let output='';const timer=setTimeout(()=>reject(Error('Agent startup timeout')),15000);
    agent.once('error',reject);agent.once('exit',code=>{clearTimeout(timer);reject(Error('Agent exited: '+code+' '+errors.join('')));});
    agent.stdout.on('data',data=>{output+=data;const match=output.match(/TEST_PORT=(\d+)/);if(match){clearTimeout(timer);resolve(Number(match[1]));}});
  });
  const endpoint=`http://127.0.0.1:${port}/mcp`;
  client=new Client({name:'local-youtube-integration',version:'1'});
  await client.connect(new StreamableHTTPClientTransport(new URL(endpoint)));
  assert.equal((await client.listTools()).tools.length,13);
  const call=async(name,args={})=>(await client.callTool({name,arguments:args})).structuredContent;
  assert.equal((await call('youtube_bridge_status')).connected,false);
  // Put the simulated provider listener before the real MAIN bridge so its
  // immediate errors cannot race the fixture. Transport/content scripts stay real.
  const extension=join(folder,'extension');
  await cp(join(root,'extension'),extension,{recursive:true,filter:source=>!/[\\/](?:node_modules|tests)(?:[\\/]|$)/.test(source)&&!source.endsWith('.tmp')});
  const manifest=JSON.parse(await readFile(join(extension,'manifest.json'),'utf8'));
  manifest.content_scripts.find(script=>script.world==='MAIN').js.unshift('local-mcp-fixture.js');
  await writeFile(join(extension,'manifest.json'),JSON.stringify(manifest));
  await writeFile(join(extension,'local-mcp-fixture.js'),`
      window.testSignedIn=true;window.testExportPage=0;
      window.__youtubeResearchPageBridgeInstalled=true; // Legacy live-tab guard.
      window.ytcfg={get:key=>({LOGGED_IN:window.testSignedIn,SESSION_INDEX:2,INNERTUBE_API_KEY:'test-page-config',INNERTUBE_CLIENT_VERSION:'2.20260101.00.00'})[key]};
      addEventListener('message',event=>{
        const v=event.data;if(event.source!==window||v?.source!=='researchtube-session-extension-content'||v.type!=='command')return;
        if(v.action==='search'||v.action==='transcript-player'&&window.testRealProvider)return;
        event.stopImmediatePropagation();let data={responses:[]};
        if(v.action==='account-state')data={signedIn:window.testSignedIn};
        if(v.action==='transcript-player')data={videoId:v.payload.videoId,selectedTrack:{trackIndex:0,languageCode:'en',name:'English',isAutoGenerated:false},segments:[{start:0,duration:2,text:'Native local MCP transcript'}],returned:1,requested:v.payload.limit};
        if(v.action==='comments-export-page'){
          const n=window.testExportPage++;data={sessionId:'exp_'+'a'.repeat(32),hasMore:n<2,records:[{videoId:v.payload.videoId,commentId:'comment'+n,parentCommentId:null,author:{name:'Public author',channelId:null},text:'Record '+n,publishedAt:null,publishedText:'today',likes:0,authorIsCreator:false,isHearted:false}]};
        }
        if(v.action==='comments-export-close')data={closed:true};
        window.postMessage({source:'researchtube-session-page-bridge',type:'command-result',payload:{id:v.id,ok:true,data}},location.origin);
      },true);
    `);
  browser=await chromium.launchPersistentContext(join(folder,'profile'),{channel:process.env.RESEARCHTUBE_BROWSER_CHANNEL||'msedge',headless:true,
    ignoreDefaultArgs:['--disable-extensions'],args:['--disable-extensions-except='+extension,'--load-extension='+extension,
      '--host-resolver-rules=MAP rtube.win 127.0.0.1, MAP www.youtube.com 127.0.0.1']});
  const nativeRequests=[];
  const video=id=>({videoRenderer:{videoId:id,title:{simpleText:'Session search result'},ownerText:{simpleText:'Test channel'}}});
  await browser.route('**/*',async route=>{
    const url=new URL(route.request().url());
    if(url.protocol==='chrome-extension:'||url.hostname==='127.0.0.1')return route.continue();
    if(url.origin==='https://www.youtube.com'){
      const headers=await route.request().allHeaders();
      nativeRequests.push({path:url.pathname,cookie:headers.cookie?.includes('SAPISID=test-session-cookie')===true,
        authorization:/^SAPISIDHASH \d+_[a-f0-9]{40}$/.test(headers.authorization||''),account:headers['x-goog-authuser']});
      if(url.pathname==='/results')return route.fulfill({contentType:'text/html',body:'<script>var ytInitialData = '+JSON.stringify({contents:[video('searchfirst'),{continuationItemRenderer:{continuationEndpoint:{continuationCommand:{token:'test-continuation'}}}}]})+';</script>'});
      if(url.pathname==='/youtubei/v1/search')return route.fulfill({json:{contents:[video('searchsecond')]}});
      if(url.pathname==='/youtubei/v1/player'){
        assert.equal(route.request().postDataJSON().context.client.clientName,'ANDROID');
        return route.fulfill({json:{captions:{playerCaptionsTracklistRenderer:{captionTracks:[{languageCode:'en',name:{simpleText:'English'},baseUrl:'https://www.youtube.com/api/timedtext?signature=PRIVATE_SIGNED_VALUE'}]}}}});
      }
      if(url.pathname==='/watch'){
        assert.equal(headers.cookie,undefined,'watch metadata/transcripts must omit cookies');
        const player={videoDetails:{videoId:'abcdefghijk',title:'Session metadata',author:'Test',lengthSeconds:'2',viewCount:'3'},
          captions:{playerCaptionsTracklistRenderer:{captionTracks:[{languageCode:'en',name:{simpleText:'English'},baseUrl:'https://www.youtube.com/api/timedtext?signature=PRIVATE_SIGNED_VALUE'}]}},
          streamingData:{formats:[{itag:18,mimeType:'video/mp4; codecs="avc1, mp4a"',url:'PRIVATE_SIGNED_VALUE'}]}};
        return route.fulfill({contentType:'text/html',body:'<script>var config={"INNERTUBE_API_KEY":"test-page-config"}; var ytInitialPlayerResponse = '+JSON.stringify(player)+'; var ytInitialData = {};</script>'});
      }
      if(url.pathname==='/api/timedtext')return route.fulfill({json:{events:[{tStartMs:0,dDurationMs:2000,segs:[{utf8:'Session caption'}]}]}});
      return route.fulfill({contentType:'text/html',body:'<!doctype html><title>Simulated YouTube</title>'});
    }
    return route.abort();
  });
  const worker=browser.serviceWorkers()[0]||await browser.waitForEvent('serviceworker',{timeout:15000});
  assert.equal(new URL(worker.url()).host,ID);
  const settings=await browser.newPage();await settings.goto(EXT+'/settings.html');
  await settings.evaluate(async port=>{await chrome.storage.local.set({agentPort:port});await chrome.alarms.create('local-mcp',{when:Date.now()+100});},port);
  for(let i=0;i<100;i++){if((await call('youtube_bridge_status')).connected)break;await settings.waitForTimeout(100);}
  assert.equal((await call('youtube_bridge_status')).connected,true,'native Extension WebSocket must pair with Agent');
  await settings.bringToFront();
  const before=await settings.evaluate(()=>chrome.tabs.query({active:true,currentWindow:true}));
  assert.equal((await settings.evaluate(()=>chrome.tabs.query({url:'https://www.youtube.com/*'}))).length,0);
  let transcript=await call('youtube_get_transcript',{videoId:'abcdefghijk',limit:10});
  // Chromium may issue an extension-created tab's first navigation before
  // Playwright attaches routing. Reissue only this simulated navigation after
  // attachment; production DNS stays blocked throughout the test.
  if(!transcript.segments){
    const tab=(await settings.evaluate(()=>chrome.tabs.query({url:'https://www.youtube.com/*'})))[0];
    assert.ok(tab);assert.equal(tab.active,false);
    const page=browser.pages().find(page=>page.url().startsWith('https://www.youtube.com/')||page.url()==='chrome-error://chromewebdata/');
    assert.ok(page);await page.goto('https://www.youtube.com/');
    transcript=await call('youtube_get_transcript',{videoId:'abcdefghijk',limit:10});
  }
  assert.equal(transcript.segments?.[0]?.text,'Native local MCP transcript',JSON.stringify(transcript));
  await call('youtube_get_transcript',{videoId:'abcdefghijk',limit:10});
  const tabs=await settings.evaluate(()=>chrome.tabs.query({url:'https://www.youtube.com/*'}));
  assert.equal(tabs.length,1);assert.equal(tabs[0].active,false);
  assert.equal((await settings.evaluate(()=>chrome.tabs.query({active:true,currentWindow:true})))[0].id,before[0].id);
  const youtube=browser.pages().find(page=>page.url().startsWith('https://www.youtube.com/'));
  await youtube.evaluate(()=>{window.testSignedIn=false;});
  assert.equal((await call('youtube_get_transcript',{videoId:'abcdefghijk'})).error.code,'YOUTUBE_LOGIN_REQUIRED');
  await youtube.evaluate(()=>{window.testSignedIn=true;});
  const task=await call('youtube_comments_export',{videoId:'abcdefghijk',maxComments:5000});
  let status=task;
  for(let i=0;i<20&&status.status==='working';i++){await settings.waitForTimeout(1000);status=await call('youtube_research_task_status',{taskId:task.taskId});}
  assert.equal(status.status,'completed',JSON.stringify(status));assert.equal(status.collected,3);
  const dataset=await call('youtube_dataset_read',{taskId:task.taskId,limit:2});
  assert.equal(dataset.returned,2);assert.equal(dataset.nextOffset,2);
  assert.equal((await call('youtube_research_task_cancel',{taskId:task.taskId})).status,'completed');
  await browser.addCookies([{name:'SAPISID',value:'test-session-cookie',url:'https://www.youtube.com',secure:true}]);
  const search=await call('youtube_search',{query:'session',limit:2});
  assert.equal(search.results?.length,2,JSON.stringify(search));
  const signed=nativeRequests.find(item=>item.path==='/youtubei/v1/search');
  assert.ok(signed,'search must traverse its continuation');
  assert.equal(signed.cookie,false);assert.equal(signed.authorization,false);assert.equal(signed.account,undefined);
  const metadata=await call('youtube_get_video',{videoId:'abcdefghijk'});
  assert.equal(metadata.title,'Session metadata',JSON.stringify(metadata));
  assert.doesNotMatch(JSON.stringify(metadata),/PRIVATE_SIGNED_VALUE|test-session-cookie|SAPISIDHASH/);
  await youtube.evaluate(()=>{window.testRealProvider=true;});
  const transcriptStart=nativeRequests.length;
  const realTranscript=await call('youtube_get_transcript',{videoId:'abcdefghijk',limit:10});
  assert.equal(realTranscript.segments?.[0]?.text,'Session caption',JSON.stringify(realTranscript));
  for(const path of ['/results','/watch']){
    const requests=nativeRequests.slice(0,transcriptStart).filter(item=>item.path===path);
    assert.ok(requests.length,'anonymous request required for '+path);
    assert.ok(requests.every(item=>!item.cookie&&!item.authorization));
  }
  for(const path of ['/watch','/youtubei/v1/player','/api/timedtext']){
    const request=nativeRequests.slice(transcriptStart).find(item=>item.path===path);
    assert.ok(request,'restored transcript request required for '+path);
    assert.equal(request.cookie,false);assert.equal(request.authorization,false);
  }
  assert.equal((await settings.evaluate(()=>chrome.tabs.query({active:true,currentWindow:true})))[0].id,before[0].id);
  assert.deepEqual(errors,[]);
  console.log('Real local MCP: anonymous search/metadata/transcripts with browser cookies present, inactive tab and export/read/cancel passed');
} finally {
  await client?.close();await browser?.close();
  if(agent&&agent.exitCode===null){await new Promise(resolve=>{agent.once('exit',resolve);agent.kill();});}
  if(dirname(folder)!==resolve(tmpdir())||!basename(folder).startsWith('researchtube-local-mcp-'))throw Error('Unexpected test directory');
  await rm(folder,{recursive:true,force:true,maxRetries:5,retryDelay:300});
}
