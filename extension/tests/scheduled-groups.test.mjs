import assert from "node:assert/strict";
import {readFile} from "node:fs/promises";
import {PLAN_TOOL_NAMES,memoryToolDefinitions} from "../scheduled-memory-tools.js";
const source=await readFile(new URL("../background.js",import.meta.url),"utf8");
assert.match(source,/const SCHEDULER_INTERVAL_MS=3000;/);
assert.doesNotMatch(source,/SCHEDULED_CONTINUATION|isScheduledGroup|createScheduledGroup/);
assert.match(source,/activePlanChats\.has\(id\)/);
assert.match(source,/activePlanChats\.delete\(id\)/);
assert.match(source,/__plan_scan/);
assert.match(source,/__plan_transition/);
assert.match(source,/planned:true/);
assert.match(source,/if \(planned && nonempty && !resumeExact\)/);
assert.match(source,/planConversationId\(live.url\)!==chatId/);
assert.equal(PLAN_TOOL_NAMES.length,12);
const defs=memoryToolDefinitions();
for(const name of PLAN_TOOL_NAMES)assert.ok(defs.find(d=>d.name===name));
assert.ok(defs.find(d=>d.name==="plan_edit").inputSchema.required.includes("operation_id"));
assert.ok(defs.find(d=>d.name==="skill_update").inputSchema.required.includes("expected_version"));
console.log("individual conversation plans and shared skills: ok");
