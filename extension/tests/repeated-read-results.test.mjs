import assert from "node:assert/strict";
import {createHash} from "node:crypto";
import {createRepeatedReadCache,REPEAT_READ_TOOLS} from "../repeated-read-results.js";
import {memoryToolDefinitions} from "../scheduled-memory-tools.js";
import {assertSchema} from "./fixtures/schema-check.mjs";
let now=10000;
const cache=createRepeatedReadCache({now:()=>now,digest:async s=>createHash("sha256").update(s).digest("hex"),ttl:1000,capacity:2});
const tool="skill_read",args={id:1,chatTabId:7},target={conversationId:"chat-a",documentId:"doc-a"};
const value={data:JSON.stringify({skill:{id:1,version:1,content:"Long method ".repeat(200)}})};
const response={structuredContent:value,content:[{type:"text",text:JSON.stringify(value)}]};
const read=(id,opts=args,t=target,r=response,name=tool)=>cache.prepare(name,opts,r,t,id);
const first=await read("r1");assert.equal(first.result,response);first.remember();
const second=await read("r2");assert.equal(second.repeated,true);assert.equal(second.result.structuredContent.previousRequestId,"r1");
assertSchema(memoryToolDefinitions().find(t=>t.name===tool).outputSchema,second.result.structuredContent);
assertSchema(memoryToolDefinitions().find(t=>t.name===tool).outputSchema,value);
assert.equal((await read("r3",{...args,force_full:true})).result,response);
assert.equal((await read("r4",args,{...target,conversationId:"chat-b"})).result,response);
assert.equal((await read("r5",args,{...target,documentId:"doc-b"})).result,response);
assert.equal((await read("r6",args,null)).result,response);
const changed={data:value.data.replace("Long method","Changed method")};
const changedResult={structuredContent:changed,content:[{type:"text",text:JSON.stringify(changed)}]};
assert.equal((await read("r7",args,target,changedResult)).result,changedResult);
const error={...response,isError:true};assert.equal((await read("err",args,target,error)).result,error);
assert.equal((await read("write",args,target,response,"skill_update")).result,response);
assert.ok(!REPEAT_READ_TOOLS.includes("plan_status"));
now+=1000;assert.equal((await read("expired")).result,response);
console.log("Repeated reads: exact comparison, TTL, conversation isolation, force_full and schema variants OK");
