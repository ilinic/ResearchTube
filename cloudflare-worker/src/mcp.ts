import { Server } from "@modelcontextprotocol/sdk/server/index.js";
import { WebStandardStreamableHTTPServerTransport } from "@modelcontextprotocol/sdk/server/webStandardStreamableHttp.js";
import { CallToolRequestSchema, CallToolResultSchema, ListToolsRequestSchema, ListResourcesRequestSchema, ReadResourceRequestSchema, McpError, ErrorCode } from "@modelcontextprotocol/sdk/types.js";
import { authenticateMcp, MCP_SCOPE, type Auth } from "./auth";
import { errorResponse, json, origin, PublicError, readJson, room, type Env } from "./types";
import { WORKER_VERSION } from "./version";
import { setupResult } from "./onboarding";

import { tools, catalog } from "./catalog";

// Compile outside request handling; do not evaluate schemas with dynamic code
// inside Workers. Standalone validation is generated by scripts/build-validators.
import validateArguments from "./validators.js";

export async function roomRequest(env: Env, userId: string, path: string, body: unknown): Promise<Record<string, unknown>> {
  const response = await room(env, userId).fetch(new Request(`https://room.internal${path}`, {
    method: "POST", headers: { "Content-Type": "application/json" }, body: JSON.stringify(body)
  }));
  const value = await response.json() as Record<string, any>;
  if (!response.ok) throw new PublicError(value.error?.code || "BROWSER_UNAVAILABLE", value.error?.message || "The browser is unavailable.", response.status);
  return value;
}
function toolResult(value: unknown, meta?: Record<string, unknown>) {
  return { content: [{ type: "text" as const, text: JSON.stringify(value) }], structuredContent: value as Record<string, unknown>, ...(meta ? { _meta: meta } : {}) };
}

export async function mcpResponse(request: Request, env: Env, auth: Auth): Promise<Response> {
  if (request.method !== "POST") return new Response(null, { status: 405, headers: { Allow: "POST" } });
  let body: any;
  try { body = await readJson(request); } catch (error) { return errorResponse(error); }
  // Authenticate before SDK dispatch, including unknown tool calls. Discovery
  // alone is public; tool execution never falls back to cookie authentication.
  let userId: string | undefined;
  if (body?.method === "tools/call") {
    try { userId = await authenticateMcp(request, env, auth); }
    catch (error) {
      if (!(error instanceof PublicError)) return errorResponse(error);
      const insufficient = error.code === "INSUFFICIENT_SCOPE";
      const challenge = `Bearer resource_metadata="${origin(env)}/.well-known/oauth-protected-resource", scope="${MCP_SCOPE}", error="${insufficient ? "insufficient_scope" : "invalid_token"}", error_description="Connect your ResearchTube account"`;
      return json({ jsonrpc: "2.0", id: body.id ?? null, error: { code: -32001, message: error.message } }, error.status,
        { "WWW-Authenticate": challenge });
    }
  }
  const server = new Server({ name: "researchtube", version: WORKER_VERSION }, {
    capabilities: { tools: {}, resources: {} },
    instructions: "Immediately call the requested productive tool. Never start with connection diagnostics or add a connection widget. Each authenticated account has one active extension; requests go straight to it. New extension enrollment replaces the previous extension. tabId/chatTabId from the startup prompt is required for chat delivery and browser actions targeting a chat. Never guess a tab or use focus. The extension pins the exact live document inside execution and refuses changed or unavailable targets. No separate connection or handshake is needed per chat. For an offline extension, report the error and ask the user to open Chrome or check the extension popup. Never automatically replay BROWSER_OUTCOME_UNKNOWN or an unacknowledged action. Local file/media tools require the optional Agent. Existing tool validation and task status/cancel semantics apply."
  });
  server.setRequestHandler(ListToolsRequestSchema, async () => ({ tools: tools as any }));
  server.setRequestHandler(ListResourcesRequestSchema, async () => ({ resources: [
    ...catalog.resources.map(({ uri, name, mimeType }) => ({ uri, name, mimeType }))
  ] }));
  server.setRequestHandler(ReadResourceRequestSchema, async ({ params }) => {
    const resource = catalog.resources.find(resource => resource.uri === params.uri);
    if (!resource) throw new McpError(ErrorCode.InvalidParams, "Unknown ResearchTube resource.");
    return { contents: [resource] };
  });
  server.setRequestHandler(CallToolRequestSchema, async ({ params }) => {
    try {
      if (!Object.hasOwn(validateArguments, params.name)) throw new PublicError("TOOL_NOT_FOUND", "Unknown ResearchTube tool.");
      const validator = (validateArguments as Record<string, any>)[params.name];
      const args = params.arguments || {};
      if (!validator(args)) throw new PublicError("INVALID_ARGUMENT", "Arguments do not match this tool's schema.");
      if (!userId) throw new PublicError("AUTHENTICATION_REQUIRED", "Connect your ResearchTube account.", 401);
      if (params.name === "system_connection_status") {
        return toolResult(setupResult(env, await roomRequest(env, userId, "/status", {})));
      }
      const response = await roomRequest(env, userId, "/dispatch", {
        request: { jsonrpc: "2.0", method: "tools/call", params: { name: params.name, arguments: args } } });
      if (response.error) throw new PublicError("BROWSER_TOOL_ERROR", "The browser could not execute this tool. Check ResearchTube diagnostics.");
      return CallToolResultSchema.parse(response.result);
    } catch (error) {
      return { ...toolResult({ error: { code: error instanceof PublicError ? error.code : "BROWSER_UNAVAILABLE",
        message: error instanceof PublicError ? error.message : "ResearchTube could not complete this browser request." } }), isError: true };
    }
  });
  const transport = new WebStandardStreamableHTTPServerTransport({ sessionIdGenerator: undefined, enableJsonResponse: true });
  await server.connect(transport);
  try { return await transport.handleRequest(request, { parsedBody: body }); }
  finally { await server.close(); }
}
